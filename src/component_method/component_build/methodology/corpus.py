"""Read and verify the frozen migration history corpus.

The corpus is produced by ``migration_scenario_validation/tools/
build_history_corpus.py``.  This module is the only place the methodology
pipeline learns where the examples live and which files play which role.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

# Fallback policy for corpora built before the spec carried an explicit
# repository policy (the windows_to_kylin corpus).  A corpus that declares
# ``policy`` in index.json overrides these; other scenarios must declare theirs.
ALLOWED_REPOS = {"libuv", "libarchive"}
HELD_OUT_REPOS = {"poco", "nginx", "curl", "opencv"}
ROLES = ("before", "after", "context", "tests")


class CorpusError(RuntimeError):
    pass


def _load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise CorpusError(f"cannot read {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise CorpusError(f"{path} must contain a JSON object")
    return value


def file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


@dataclass(frozen=True)
class HistoryExample:
    task_id: str
    root: Path
    workspace: Path
    metadata: dict[str, Any]
    scenario: str = ""

    @property
    def files(self) -> dict[str, list[str]]:
        return self.metadata.get("files") or {}

    @property
    def source(self) -> dict[str, Any]:
        return self.metadata.get("source") or {}

    @property
    def capability(self) -> str:
        return str(self.metadata.get("capability") or "")

    @property
    def packet_path(self) -> Path:
        return self.root / (self.metadata.get("packet") or {}).get(
            "path", "inputs/focus_context_packets.json"
        )

    def load_packet(self) -> dict[str, Any]:
        payload = _load_json(self.packet_path)
        packets = payload.get("packets") or []
        if len(packets) != 1:
            raise CorpusError(
                f"{self.task_id} packet must contain exactly one packet, found {len(packets)}"
            )
        return payload


@dataclass(frozen=True)
class HistoryCorpus:
    root: Path
    index: dict[str, Any]
    examples: tuple[HistoryExample, ...]

    def example(self, task_id: str) -> HistoryExample:
        for example in self.examples:
            if example.task_id == task_id:
                return example
        raise CorpusError(f"unknown history example: {task_id}")


def load_corpus(root: Path) -> HistoryCorpus:
    root = root.expanduser().resolve()
    index_path = root / "index.json"
    if not index_path.is_file():
        raise CorpusError(
            f"history index is missing: {index_path}; "
            "run tools/build_history_corpus.py first"
        )
    index = _load_json(index_path)
    if index.get("schema") != "migration-history-corpus-v1":
        raise CorpusError(f"unsupported history index schema: {index.get('schema')!r}")
    raw_examples = index.get("examples") or []
    if not raw_examples:
        raise CorpusError(f"history index has no examples: {index_path}")

    scenario = str(index.get("scenario") or "")
    policy = index.get("policy") or {}
    allowed = {
        str(item).lower()
        for item in (
            policy["library_source_repos"]
            if "library_source_repos" in policy
            else ALLOWED_REPOS
        )
    }
    held_out = {
        str(item).lower()
        for item in (
            policy["held_out_repos"] if "held_out_repos" in policy else HELD_OUT_REPOS
        )
    }
    if not allowed:
        raise CorpusError(f"history index declares no library_source_repos: {index_path}")
    overlap = allowed & held_out
    if overlap:
        raise CorpusError(
            f"history repository policy is contradictory: {sorted(overlap)}"
        )

    examples: list[HistoryExample] = []
    seen: set[str] = set()
    for item in raw_examples:
        task_id = str(item.get("task_id") or "")
        if not task_id or task_id in seen:
            raise CorpusError(f"invalid or duplicate history task_id: {task_id!r}")
        seen.add(task_id)
        example_root = root / "examples" / task_id
        metadata_path = example_root / "example.json"
        if not metadata_path.is_file():
            raise CorpusError(f"history example metadata is missing: {metadata_path}")
        metadata = _load_json(metadata_path)
        if metadata.get("generated_by") != "tools/build_history_corpus.py":
            raise CorpusError(f"history example is not generated by the corpus tool: {task_id}")
        repo = str((metadata.get("source") or {}).get("repo") or "")
        name = repo.rstrip("/").rsplit("/", 1)[-1]
        if name.endswith(".git"):
            name = name[:-4]
        if name.lower() in held_out:
            raise CorpusError(f"held-out repository must not enter history: {name}")
        if name.lower() not in allowed:
            raise CorpusError(
                f"history repository {name!r} is not declared library_source "
                f"for this corpus: {sorted(allowed)}"
            )
        workspace = example_root / str(metadata.get("workspace") or "repo")
        if not workspace.is_dir():
            raise CorpusError(f"history workspace is missing: {workspace}")
        for role in ROLES:
            for relative in (metadata.get("files") or {}).get(role) or []:
                if not (workspace / relative).is_file():
                    raise CorpusError(
                        f"{task_id} role file is missing from the workspace: {relative}"
                    )
        for role in ("before", "after"):
            if not (metadata.get("files") or {}).get(role):
                raise CorpusError(f"{task_id} has no {role} files")
        packet_info = metadata.get("packet") or {}
        packet_path = example_root / packet_info.get("path", "inputs/focus_context_packets.json")
        if not packet_path.is_file():
            raise CorpusError(f"{task_id} packet is missing: {packet_path}")
        expected_sha = packet_info.get("sha256")
        if expected_sha and file_sha256(packet_path) != expected_sha:
            raise CorpusError(f"{task_id} packet does not match its recorded digest")
        examples.append(
            HistoryExample(
                task_id=task_id,
                root=example_root,
                workspace=workspace,
                metadata=metadata,
                scenario=scenario,
            )
        )
    return HistoryCorpus(root=root, index=index, examples=tuple(examples))


def corpus_digest(root: Path) -> str:
    """Hash the corpus index, every example manifest and every packet."""
    root = root.expanduser().resolve()
    digest = hashlib.sha256()
    index_path = root / "index.json"
    if not index_path.is_file():
        raise CorpusError(f"history index is missing: {index_path}")
    files = [index_path]
    examples_root = root / "examples"
    if examples_root.is_dir():
        for example_root in sorted(path for path in examples_root.iterdir() if path.is_dir()):
            files.extend(
                path
                for path in (
                    example_root / "example.json",
                    example_root / "inputs" / "focus_context_packets.json",
                )
                if path.is_file()
            )
    for path in files:
        digest.update(path.relative_to(root).as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update(file_sha256(path).encode("ascii"))
        digest.update(b"\n")
    return digest.hexdigest()


def verify_corpus(root: Path) -> dict[str, Any]:
    """Check corpus integrity without running any agent."""
    corpus = load_corpus(root)
    digest = corpus_digest(root)
    packets = []
    for example in corpus.examples:
        payload = example.load_packet()
        packet = payload["packets"][0]
        focus = set(packet.get("focus_files") or [])
        expected = set(example.files.get("after") or [])
        if focus != expected:
            raise CorpusError(
                f"{example.task_id} focus files do not match the after role: "
                f"{sorted(focus ^ expected)}"
            )
        packets.append(
            {
                "task_id": example.task_id,
                "capability": example.capability,
                "repo": example.source.get("repo"),
                "commit": example.source.get("commit"),
                "focus_files": len(focus),
                "focus_units": packet.get("focus_unit_count"),
                "context_units": packet.get("context_unit_count"),
                "fallback_files": packet.get("fallback_file_count", 0),
            }
        )
    return {
        "schema": "migration-history-verify-v1",
        "root": str(corpus.root),
        "digest": digest,
        "example_count": len(corpus.examples),
        "examples": packets,
    }