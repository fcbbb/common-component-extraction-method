"""Small backend capabilities; registration does not imply runtime support."""

from pathlib import Path
from typing import Any, Iterable, Protocol

from .contracts import (
    BackendIdentity, ComponentArtifact, Diagnostic, ExecutionObservation,
    ProcessResult, PublishedComponent, RuntimeInvocation, SmokeCase, SourceUnit,
    SourceUnitRef, TaskEnvironmentSpec, TokenStream, UnitProfile,
)


class SourceBackend(Protocol):
    language_id: str
    backend_id: str

    def identity(self) -> BackendIdentity: ...
    def scan_policy(self) -> dict[str, Any]: ...
    def eligible_files(self, root: Path, source_subdir: str) -> Iterable[Path]: ...
    def extract_units(self, file_id: str, source: str) -> list[SourceUnit]: ...
    def validate_source(self, file_id: str, source: str) -> list[Diagnostic]: ...


class SignalBackend(Protocol):
    def file_token_streams(self, file_id: str, source: str,
                           signal: str) -> tuple[list[TokenStream], str | None]: ...
    def normalized_tokens(self, unit: SourceUnit) -> TokenStream: ...
    def structural_tokens(self, unit: SourceUnit) -> TokenStream: ...
    def build_profile(self, unit: SourceUnit) -> UnitProfile: ...
    def is_ancestor(self, parent: SourceUnit | dict[str, Any],
                     child: SourceUnit | dict[str, Any]) -> bool: ...
    def describe_unit_id(self, unit_id: str) -> dict[str, Any]: ...


class ArtifactBackend(Protocol):
    def validate_artifact(self, artifact: ComponentArtifact) -> list[Diagnostic]: ...
    def validate_entrypoints(self, artifact: ComponentArtifact) -> list[Diagnostic]: ...
    def validate_grounding(self, artifact: ComponentArtifact, repository: Path,
                           members: list[SourceUnitRef]) -> list[Diagnostic]: ...


class RuntimeBackend(Protocol):
    def toolchain_probes(self) -> tuple[tuple[str, ...], ...]: ...
    def prepare_smoke(self, artifact: ComponentArtifact, case: SmokeCase,
                      workspace: Path) -> RuntimeInvocation: ...
    def parse_observations(self, invocation: RuntimeInvocation,
                           result: ProcessResult) -> list[ExecutionObservation]: ...


class PublicationBackend(Protocol):
    def materialize_component(self, artifact: ComponentArtifact,
                              destination: Path) -> PublishedComponent: ...
    def render_loading_instructions(self, published: PublishedComponent) -> str: ...


class TaskBackend(Protocol):
    def task_environment(self, task: dict[str, Any], bundle: Path | None) -> TaskEnvironmentSpec: ...
    def validate_repository_edits(self, repository: Path) -> list[Diagnostic]: ...
